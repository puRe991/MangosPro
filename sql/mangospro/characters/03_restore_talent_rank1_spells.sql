INSERT IGNORE INTO character_spell (guid, spell, active, disabled)
SELECT DISTINCT cs.guid, m.talent_spell, 0, 0
FROM character_spell cs
JOIN mp_talent_rank_map m ON m.rank_spell = cs.spell
WHERE cs.disabled = 0
  AND NOT EXISTS (SELECT 1 FROM character_spell t WHERE t.guid = cs.guid AND t.spell = m.talent_spell);

